"""AuditManager - runs tests on a Browser."""

import logging
import os
import urllib.parse
from typing import Any

import selenium.common.exceptions
import urllib3

from config import Config, SiteData
from src.audit_plugins.default_audit import DefaultAudit
from src.browser import Browser
from src.output import CSVWriter

logger = logging.getLogger('cwac')


class AuditManager:
  """Runs tests on browsers."""

  def __init__(self, config: Config, browser: Browser) -> None:
    """Init variables."""
    self.config = config
    self.browser = browser
    self.audits: dict[str, type[DefaultAudit]] = {}

    # Stores URLs discarded as a key-value pair
    # of URL (str): reason (str). URLs are discarded
    # if they are blocked by anti-bot measures.
    self.discarded_urls: dict[str, str] = {}

  def register_audit(
    self,
    audit_name: str,
    audit_class: type[DefaultAudit],
  ) -> None:
    """Register audits to be run by run_audits().

    Registering an audit with an existing name replaces it.

    Args:
        audit_name (str): Human-readable name for audit
        audit_class (type[DefaultAudit]): Reference to a class that runs the audit
    """
    self.audits[audit_name] = audit_class

  def test_for_anti_bot(self, site_data: SiteData) -> str:
    """Inspect the currently loaded page for anti-bot blocking.

    If bot blocking services such as Cloudflare, Incapsula, Azure Front Door,
    etc. are detected then:

    1. A screenshot is saved to the 'anti_bot_ss' folder.
    2. The result is written to an 'anti_bot.csv' file.
    3. The URL is added to the discarded_urls dict with the reason for discarding.

    Returns:
      str: 'Pass'|'Imperva'|'Cloudflare'|'Azure Front Door'|'Red Shield'|'Cloudfront'
    """
    # Get the current URL
    try:
      url = self.browser.driver.current_url
    except (
      selenium.common.exceptions.WebDriverException,
      urllib3.exceptions.HTTPError,
    ) as e:
      logger.error('%s when getting current URL', type(e).__name__)
      return 'Pass'

    # If the URL is already discarded return its result
    if url in self.discarded_urls:
      return self.discarded_urls[url]

    # Get the page source
    try:
      page_source = self.browser.driver.page_source
    except (
      selenium.common.exceptions.WebDriverException,
      urllib3.exceptions.HTTPError,
    ) as e:
      logger.error('%s when getting page source', type(e).__name__)
      return 'Pass'

    status = 'Pass'

    # Check for 'Incapsula' in the page source
    if 'Incapsula incident ID' in page_source:
      logger.error('Incapsula detected on %s', url)
      status = 'Imperva'

    # Check for 'red-shield.net' in the page source
    if 'please email support@red-shield.net' in page_source:
      logger.error('Red Shield detected on %s', url)
      status = 'Red Shield'

    # Check for 'Cloudflare' in the page source
    if 'Verifying you are human' in page_source and 'Ray ID' in page_source:
      logger.error('Cloudflare detected on %s', url)
      status = 'Cloudflare'

    # Check for 'CloudFront' in the page source
    if 'Generated by cloudfront (CloudFront)' in page_source:
      logger.error('CloudFront detected on %s', url)
      status = 'Cloudfront'

    # Check for 'Azure Front Door' in the page source
    afd_sig = """The request is blocked.</h2></div><div id="errorref">"""
    if afd_sig in page_source:
      logger.error('Azure Front Door detected on %s', url)
      status = 'Azure Front Door'

    if status != 'Pass':
      # Get URL's netloc
      netloc = urllib.parse.urlparse(url).netloc

      # Save screenshot
      # Make screenshot directory if it doesn't exist
      os.makedirs(
        f'./results/{self.config.audit_name}/anti_bot_ss',
        exist_ok=True,
      )
      try:
        self.browser.driver.save_screenshot(f'./results/{self.config.audit_name}/anti_bot_ss/{netloc}.png')
      except (selenium.common.exceptions.WebDriverException, urllib3.exceptions.HTTPError):
        logger.exception('Failed to save anti-bot screenshot %s', url)

      # Write to anti-bot.csv
      csv_writer = CSVWriter()
      csv_writer.append_rows(
        f'./results/{self.config.audit_name}/anti_bot.csv',
        {
          **site_data['columns'],
          'url': url,
          'domain': netloc,
          'anti_bot_check': status,
          'viewport_size': self.browser.viewport_size,
        },
      )

      self.discarded_urls[url] = status

    return status

  def _check_for_closed_details_elements(self) -> None:
    """Check for closed <details> elements on current page, and open them if force_open_details_elements is True."""
    num_of_details = self.browser.driver.execute_script(
      """
      const details = document.querySelectorAll('details:not([open])');
      if(arguments[0]) {
        details.forEach(d => d.open = true);
      }
      return details.length;
    """,
      self.config.force_open_details_elements,
    )

    if num_of_details == 0:
      return

    plural = ''
    if num_of_details != 1:
      plural = 's'

    if not self.config.force_open_details_elements:
      logger.info('ignored %i closed <details> element%s', num_of_details, plural)
      return

    logger.info('opened %i <details> element%s', num_of_details, plural)

  def run_audits(self, url: str, site_data: SiteData) -> bool:
    """Iterate through registered audits and runs them.

    Main entry point for running audits. Iterates through all registered audits
    and runs them on the current page at each configured viewport size.

    For each configured viewport size:

    1. The browser window is resized to the specified dimensions.
    2. For each audit configured to run at the current viewport size:
      1. The page is (re)loaded.
      2. The antibot check is run. If the page is blocked, the audit is skipped.
      3. if force_open_details_elements is True, any closed <details> elements on the page are opened.
      4. The audit is run and the results are written to a CSV file.

    If an exception is raised during the execution of an audit, then the browser
    state is reset for the next audit:

    1. The browser is restarted.
    2. the viewport size is set again.

    Args:
        url (str): the URL of the page to audit
        site_data (SiteData): data about the site the page belongs to

    Returns:
        bool: True if at least one audit successfully produced results, else False
    """
    logger.info('run_audits called')

    # Unique UUID string
    page_id = self.config.get_unique_id()

    # Tracks if at least one audit successfully produced results
    any_audit_succeeded = False

    # Re-run tests for each viewport size in config.json
    for viewport in self.config.viewport_sizes:
      # Generate a unique audit ID
      audit_id = page_id + '_' + viewport

      self.browser.set_window_size(
        self.config.viewport_sizes[viewport]['width'],
        self.config.viewport_sizes[viewport]['height'],
      )

      for audit_name, audit in self.audits.items():
        # if viewport_to_test is set
        if (
          'viewport_to_test' in self.config.audit_plugins[audit_name]
          and self.config.audit_plugins[audit_name]['viewport_to_test'] != viewport
        ):
          # If the viewport is not the one we want to test, skip
          continue

        # Log the start of this audit
        logger.info(
          'Starting audit %s on %s',
          audit_name,
          url,
        )

        # The first time through this loop, we load the page to ensure that the
        # page is loaded with the correct viewport size. On subsequent
        # iterations, we load the page again to ensure that any changes (e.g.
        # injected JS) made by a previous audit do not affect the next audit.
        browser_status = self.browser.get(url)

        # Test for anti-bot measures
        if self.test_for_anti_bot(site_data) != 'Pass':
          # If URL is blocked, skip this URL
          logger.warning(
            'Skipping test %s on %s due to anti-bot',
            audit_name,
            url,
          )
          return any_audit_succeeded

        # If the browser fails to load the page, skip test
        if browser_status is False:
          logger.warning(
            'Skipping test %s on %s due to .get failure',
            audit_name,
            url,
          )
          continue

        # Run the tests
        audit_instance = audit(
          config=self.config,
          browser=self.browser,
          audit_id=audit_id,
          page_id=page_id,
          url=url,
          site_data=site_data,
        )

        try:
          self._check_for_closed_details_elements()

          audit_result: list[dict[str, Any]] | bool = audit_instance.run()
        except Exception:  # pylint: disable=broad-exception-caught
          logger.exception(
            'test %s skipped on viewport %s for website %s',
            audit_name,
            viewport,
            url,
          )
          # If the browser crashes, skip this test
          # and restart the browser
          self.browser.safe_restart()

          # Set window size
          self.browser.set_window_size(
            self.config.viewport_sizes[viewport]['width'],
            self.config.viewport_sizes[viewport]['height'],
          )

          continue

        logger.info('Test finished %s, %s', audit_name, url)

        # If audit_result is the boolean value True
        # a 'True' from the audit means to skip the audit
        # because it is not applicable to the current page,
        # but the audit did not fail to execute
        if audit_result is True:
          logger.info(
            'Skipping audit %s, %s',
            audit_name,
            url,
          )
          continue

        # If a test fails, .run() returns False
        if audit_result is False:
          logger.error(
            'Test failed %s, %s',
            audit_name,
            url,
          )
          continue

        # If a test returns an empty result, log an error
        if audit_result == []:
          logger.error(
            'Test gave empty response %s, %s',
            audit_name,
            url,
          )
          continue

        # Write results
        csv_writer = CSVWriter()
        csv_writer.append_rows(f'./results/{self.config.audit_name}/{audit_name}.csv', *audit_result)

        # At least one audit successfully produced results
        any_audit_succeeded = True

    return any_audit_succeeded
